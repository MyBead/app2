const OTHER: CategoryInfo = { id: 'other', label: 'Другое', emoji: '🛒', keywords: [] };

const BY_ID = new Map<CategoryId, CategoryInfo>([...CATEGORIES, OTHER].map((c) => [c.id, c]));

export const ALL_CATEGORIES: CategoryInfo[] = [...CATEGORIES, OTHER];

export function categoryInfo(id: CategoryId): CategoryInfo {
  return BY_ID.get(id) ?? OTHER;
}

/** Weight of the first word: Polish product names lead with what the product is ("Karma dla psów z kurczakiem"). */
const HEAD_WEIGHT = 3;

/** Guesses a category from a Polish product name (plus optional subtitle or store category hint). */
export function classify(...texts: (string | undefined)[]): CategoryId {
  // "Dobra Karma" is a food brand, not pet food.
  const tokens = texts.flatMap((t) => (t ? words(t.replace(/dobra karma/gi, 'dobrakarma')) : []));
  if (tokens.length === 0) return 'other';
  let best: CategoryId = 'other';
  let bestScore = 0;
  for (const cat of CATEGORIES) {
    let score = 0;
    tokens.forEach((token, i) => {
      // Short keywords ("ser", "sok", "gin") must match whole words, longer ones as prefixes.
      if (cat.keywords.some((k) => (k.length <= 3 ? token === k : token.startsWith(k))))
        score += i === 0 ? HEAD_WEIGHT : 1;
    });
    if (score > bestScore) {
      best = cat.id;
      bestScore = score;
    }
  }
  return best;
}
