const OTHER: CategoryInfo = { id: 'other', label: 'Другое', emoji: '🛒', keywords: [] };

const BY_ID = new Map<CategoryId, CategoryInfo>([...CATEGORIES, OTHER].map((c) => [c.id, c]));

export const ALL_CATEGORIES: CategoryInfo[] = [...CATEGORIES, OTHER];

export function categoryInfo(id: CategoryId): CategoryInfo {
  return BY_ID.get(id) ?? OTHER;
}

/** Guesses a category from a Polish product name (plus optional store category hint). */
export function classify(...texts: (string | undefined)[]): CategoryId {
  const tokens = texts.flatMap((t) => (t ? words(t) : []));
  if (tokens.length === 0) return 'other';
  let best: CategoryId = 'other';
  let bestHits = 0;
  for (const cat of CATEGORIES) {
    let hits = 0;
    for (const token of tokens) {
      // Short keywords ("ser", "sok", "gin") must match whole words, longer ones as prefixes.
      if (cat.keywords.some((k) => (k.length <= 3 ? token === k : token.startsWith(k)))) hits++;
    }
    if (hits > bestHits) {
      best = cat.id;
      bestHits = hits;
    }
  }
  return best;
}
